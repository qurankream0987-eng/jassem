/**
 * JASIM FROZEN GENERALITY BENCHMARK — v1.
 *
 * ─── FROZEN MEANS FROZEN ────────────────────────────────────────────────────
 *
 * Ids are permanent. A scenario is never edited to make a build pass and never
 * reused for a different scenario — it is superseded by a new id in a new
 * version. `frozen-corpus.test.ts` pins the corpus digest, so any edit at all
 * fails loudly and has to be an explicit, reviewed decision rather than a quiet
 * one.
 *
 * That rule exists because the failure mode of every benchmark is the benchmark
 * drifting toward whatever the system already does. A candidate improvement
 * that cannot pass must not be able to redefine passing — which is also the
 * Core Evolution gate (§18 of the brief) stated as a file property.
 *
 * ─── S01–S30 ENCODE THE 30 ACCEPTANCE EXAMPLES ──────────────────────────────
 *
 * Encode, not copy. The examples are written in domain language because a
 * product owner wrote them about real situations. Each is translated here into
 * the generic vocabulary the runtime actually has. If that translation ever
 * becomes impossible for a new example, that is the generality signal the
 * 30-example document describes — and it is better to discover it in a schema
 * than in a shipped feature.
 *
 * A01–A12 are adversarial variants. They exist because the 30 examples describe
 * what JASIM should do, and a benchmark also has to describe what it must
 * refuse.
 */

